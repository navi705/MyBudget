/// The seed language to use for [languageCode], which is a bare language code
/// like `ru` - the region never changes a seeded name. Falls back to English.
String seedLanguageOf(String languageCode) =>
    seedNameTranslations.containsKey(languageCode) ? languageCode : 'en';

/// [englishName] in [languageCode]. A name with no translation is returned as
/// it stands, so a seed entry added without translations still seeds.
String seedName(String languageCode, String englishName) =>
    seedNameTranslations[seedLanguageOf(languageCode)]?[englishName] ??
    englishName;
